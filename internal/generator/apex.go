package generator

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/antlr4-go/antlr/v4"
	"github.com/octoberswimmer/apexfmt/parser"
)

type syntaxErrors struct {
	*antlr.DefaultErrorListener
	failed bool
}

func (s *syntaxErrors) SyntaxError(antlr.Recognizer, interface{}, int, int, string, antlr.RecognitionException) {
	s.failed = true
}

func parseApex(path string) (parser.IClassDeclarationContext, error) {
	invalid := fmt.Errorf("invalid Apex source")
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("cannot read Apex source")
	}
	listener := &syntaxErrors{DefaultErrorListener: antlr.NewDefaultErrorListener()}
	lexer := parser.NewApexLexer(antlr.NewInputStream(string(data)))
	lexer.RemoveErrorListeners()
	lexer.AddErrorListener(listener)
	stream := antlr.NewCommonTokenStream(lexer, antlr.TokenDefaultChannel)
	p := parser.NewApexParser(stream)
	p.RemoveErrorListeners()
	p.AddErrorListener(listener)
	unit := p.CompilationUnit()
	if listener.failed || unit.TypeDeclaration() == nil || unit.TypeDeclaration().ClassDeclaration() == nil {
		return nil, invalid
	}
	class := unit.TypeDeclaration().ClassDeclaration()
	name := class.Id().GetText()
	if !apiName.MatchString(name) || !strings.EqualFold(strings.TrimSuffix(filepath.Base(path), filepath.Ext(path)), name) {
		return nil, invalid
	}
	return class, nil
}

func apexDeclaration(class *apexClass, types *apexTypes) (File, error) {
	invalid := fmt.Errorf("invalid Apex source")
	var text strings.Builder
	fmt.Fprintln(&text, "// Generated by sf-typings. Do not edit.")
	seen := make(map[string]bool)
	for _, decl := range class.node.ClassBody().AllClassBodyDeclaration() {
		member := decl.MemberDeclaration()
		if member == nil || member.MethodDeclaration() == nil {
			continue
		}
		enabled, accessible, static, _ := apexModifiers(decl.AllModifier())
		if !enabled || !accessible || !static {
			continue
		}
		method := member.MethodDeclaration()
		methodName := method.MethodId().GetText()
		if !apiName.MatchString(methodName) || seen[strings.ToLower(methodName)] {
			return File{}, invalid
		}
		seen[strings.ToLower(methodName)] = true
		var params []string
		paramNames := make(map[string]bool)
		if list := method.FormalParameters().FormalParameterList(); list != nil {
			for _, param := range list.AllFormalParameter() {
				paramName := param.Id().GetText()
				key := strings.ToLower(paramName)
				if !apiName.MatchString(paramName) || paramNames[key] {
					return File{}, invalid
				}
				paramNames[key] = true
				value, err := types.resolve(param.TypeRef(), class)
				if err != nil {
					return File{}, err
				}
				params = append(params, fmt.Sprintf("%s: %s", paramName, value))
			}
		}
		ret := "void"
		if method.VOID() == nil {
			var err error
			ret, err = types.resolve(method.TypeRef(), class)
			if err != nil {
				return File{}, err
			}
		}
		fmt.Fprintf(&text, "declare module '@salesforce/apex/%s.%s' {\n", class.name, methodName)
		if len(params) == 0 {
			fmt.Fprintf(&text, "  export default function %s(): Promise<%s>;\n", methodName, ret)
		} else {
			fmt.Fprintf(&text, "  export default function %s(params: { %s }): Promise<%s>;\n", methodName, strings.Join(params, "; "), ret)
		}
		fmt.Fprintln(&text, "}")
	}
	return File{class.name + ".d.ts", []byte(text.String())}, nil
}

// ApexOutputs renders sorted local Apex sources, rejecting duplicate classes.
func ApexOutputs(sources []string) ([]File, error) {
	var paths []string
	for _, source := range sources {
		info, err := os.Lstat(source)
		if err != nil {
			return nil, fmt.Errorf("cannot read Apex source")
		}
		if info.IsDir() {
			err = filepath.WalkDir(source, func(path string, entry os.DirEntry, err error) error {
				if err != nil {
					return err
				}
				if !entry.IsDir() && strings.EqualFold(filepath.Ext(path), ".cls") {
					paths = append(paths, path)
				}
				return nil
			})
			if err != nil {
				return nil, fmt.Errorf("cannot read Apex source")
			}
		} else if info.Mode().IsRegular() && strings.EqualFold(filepath.Ext(source), ".cls") {
			paths = append(paths, source)
		} else {
			return nil, fmt.Errorf("invalid Apex source path")
		}
	}
	sort.Strings(paths)
	types := &apexTypes{classes: make(map[string]*apexClass)}
	var classes []*apexClass
	seen := make(map[string]bool)
	for _, path := range paths {
		node, err := parseApex(path)
		if err != nil {
			return nil, err
		}
		name := node.Id().GetText()
		key := strings.ToLower(name)
		if seen[key] {
			return nil, fmt.Errorf("duplicate Apex class")
		}
		seen[key] = true
		class, err := types.add(node, nil, name)
		if err != nil {
			return nil, err
		}
		classes = append(classes, class)
	}
	types.index()
	var result []File
	for _, class := range classes {
		f, err := apexDeclaration(class, types)
		if err != nil {
			return nil, err
		}
		result = append(result, f)
	}
	// Render only after all method roots have walked the shared wrapper graph.
	for i, class := range classes {
		result[i].Data = append(result[i].Data, []byte(types.declarations(class.name))...)
	}
	return result, nil
}
