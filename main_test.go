func TestMain(m *testing.M) {
	if os.Getenv("SF_TYPINGS_MOCK") == "1" {
		if len(os.Args) != 8 || strings.Join(os.Args[1:3], " ") != "sobject describe" || os.Args[3] != "--sobject" || os.Args[5] != "--target-org" {
			fmt.Fprintln(os.Stderr, "unexpected sf arguments")
			os.Exit(3)
		}
		if err := os.WriteFile(os.Getenv("SF_TYPINGS_LOG"), []byte(strings.Join(os.Args[1:], " ")), 0600); err != nil {
			os.Exit(4)
		}
		if os.Getenv("SF_TYPINGS_RESPONSE") == "__fail__" {
			fmt.Fprintln(os.Stderr, "mock secret")
			os.Exit(7)
		}
		if os.Getenv("SF_TYPINGS_RESPONSE") == "__second_invalid__" {
			if os.Args[4] == "Account" {
				fmt.Print(`{"status":0,"result":{"name":"Account","fields":[]}}`)
			} else {
				fmt.Print(`{"status":0,"result":{"name":"Wrong","fields":[]}}`)
			}
			os.Exit(0)
		}
		fmt.Print(os.Getenv("SF_TYPINGS_RESPONSE"))
		os.Exit(0)
	}
	os.Exit(m.Run())
}

func fixture(t *testing.T, config any, response string) (string, string, []string) {
	t.Helper()
	root := t.TempDir()
	b, err := json.Marshal(config)
	if err != nil {
		t.Fatal(err)
	}
	configPath := filepath.Join(root, "config.json")
	if err := os.WriteFile(configPath, b, 0600); err != nil {
		t.Fatal(err)
	}
	mock := filepath.Join(root, "sf")
	if runtime.GOOS == "windows" {
		mock += ".exe"
	}
	self, err := os.Executable()
	if err != nil {
		t.Fatal(err)
	}
	content, err := os.ReadFile(self)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(mock, content, 0700); err != nil {
		t.Fatal(err)
	}
	binary := filepath.Join(root, "sf-typings")
	if runtime.GOOS == "windows" {
		binary += ".exe"
	}
	build := exec.Command("go", "build", "-o", binary, ".")
	if output, err := build.CombinedOutput(); err != nil {
		t.Fatalf("build: %v: %s", err, output)
	}
	return root, binary, []string{"-config", configPath, "-out", filepath.Join(root, "generated")}
}

func runCLI(t *testing.T, root, binary, response string, args ...string) (string, string, int) {
	t.Helper()
	cmd := exec.Command(binary, args...)
	cmd.Env = append(os.Environ(), "PATH="+root+string(os.PathListSeparator)+os.Getenv("PATH"), "SF_TYPINGS_MOCK=1", "SF_TYPINGS_RESPONSE="+response, "SF_TYPINGS_LOG="+filepath.Join(root, "invoked"), "HOME="+root, "USERPROFILE="+root)
	var stdout, stderr strings.Builder
	cmd.Stdout, cmd.Stderr = &stdout, &stderr
	err := cmd.Run()
	if err == nil {
		return stdout.String(), stderr.String(), 0
	}
	if e, ok := err.(*exec.ExitError); ok {
		return stdout.String(), stderr.String(), e.ExitCode()
	}
	t.Fatal(err)
	return "", "", -1
}

func TestPublicCLI(t *testing.T) {
	describe := `{"status":0,"result":{"name":"Account","fields":[{"name":"Name","type":"string","nillable":false},{"name":"AnnualRevenue","type":"currency","nillable":true},{"name":"IsActive__c","type":"boolean","nillable":false}],"extra":{"kept":true}}}`
	config := map[string]any{"orgAlias": "dev", "objects": []string{"Account"}}
	t.Run("success and snapshots", func(t *testing.T) {
		root, binary, args := fixture(t, config, describe)
		args = append(args, "-snapshots")
		out, errs, status := runCLI(t, root, binary, describe, args...)
		if out != "Generated 1 object(s).\n" || errs != "" || status != 0 {
			t.Fatalf("stdout=%q stderr=%q exit=%d", out, errs, status)
		}
		decl, err := os.ReadFile(filepath.Join(root, "generated", "Account.d.ts"))
		if err != nil {
			t.Fatal(err)
		}
		want := "// Generated by sf-typings. Do not edit.\nexport interface Account {\n  AnnualRevenue?: number | null;\n  IsActive__c?: boolean;\n  Name?: string;\n}\n"
		if string(decl) != want {
			t.Fatalf("declaration=%q want=%q", decl, want)
		}
		snapshot, err := os.ReadFile(filepath.Join(root, "generated", "Account.describe.json"))
		if err != nil {
			t.Fatal(err)
		}
		if !strings.Contains(string(snapshot), `"extra": {`) {
			t.Fatalf("snapshot lost extra: %s", snapshot)
		}
		invocation, err := os.ReadFile(filepath.Join(root, "invoked"))
		if err != nil {
			t.Fatal(err)
		}
		if string(invocation) != "sobject describe --sobject Account --target-org dev --json" {
			t.Fatalf("invocation=%q", invocation)
		}
	})
	t.Run("invalid config does not invoke sf or overwrite", func(t *testing.T) {
		root, binary, args := fixture(t, map[string]any{"orgAlias": "dev", "objects": []string{"../Account"}}, describe)
		dest := filepath.Join(root, "generated")
		if err := os.Mkdir(dest, 0700); err != nil {
			t.Fatal(err)
		}
		existing := filepath.Join(dest, "Account.d.ts")
		if err := os.WriteFile(existing, []byte("original"), 0600); err != nil {
			t.Fatal(err)
		}
		out, errs, status := runCLI(t, root, binary, describe, args...)
		if out != "" || errs != "sf-typings: invalid object API name\n" || status != 1 {
			t.Fatalf("stdout=%q stderr=%q exit=%d", out, errs, status)
		}
		b, _ := os.ReadFile(existing)
		if string(b) != "original" {
			t.Fatalf("existing=%q", b)
		}
		if _, err := os.Stat(filepath.Join(root, "invoked")); !os.IsNotExist(err) {
			t.Fatalf("sf invoked: %v", err)
		}
	})
	for _, tc := range []struct {
		name              string
		config            any
		response, message string
		invoked           bool
	}{
		{"invalid org", map[string]any{"orgAlias": "dev;echo secret", "objects": []string{"Account"}}, describe, "invalid org alias", false},
		{"duplicate objects", map[string]any{"orgAlias": "dev", "objects": []string{"Account", "Account"}}, describe, "duplicate object API name", false},
		{"sf error status", config, `{"status":1,"result":{"name":"Account","fields":[]}}`, "invalid describe for Account", true},
		{"wrong name", config, `{"status":0,"result":{"name":"Contact","fields":[]}}`, "invalid describe for Account", true},
		{"malicious field", config, `{"status":0,"result":{"name":"Account","fields":[{"name":"X; bad","type":"string","nillable":false}]}}`, "invalid describe for Account", true},
		{"sf process failure hides stderr", config, "__fail__", "sf describe failed for Account", true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			root, binary, args := fixture(t, tc.config, tc.response)
			dest := filepath.Join(root, "generated")
			if err := os.Mkdir(dest, 0700); err != nil {
				t.Fatal(err)
			}
			existing := filepath.Join(dest, "Account.d.ts")
			if err := os.WriteFile(existing, []byte("original"), 0600); err != nil {
				t.Fatal(err)
			}
			out, errs, status := runCLI(t, root, binary, tc.response, args...)
			if out != "" || errs != "sf-typings: "+tc.message+"\n" || status != 1 {
				t.Fatalf("stdout=%q stderr=%q exit=%d", out, errs, status)
			}
			b, _ := os.ReadFile(existing)
			if string(b) != "original" {
				t.Fatalf("existing=%q", b)
			}
			_, err := os.Stat(filepath.Join(root, "invoked"))
			if (err == nil) != tc.invoked {
				t.Fatalf("sf invocation: %v", err)
			}
		})
	}
	t.Run("second describe failure preserves first output", func(t *testing.T) {
		root, binary, args := fixture(t, map[string]any{"orgAlias": "dev", "objects": []string{"Contact", "Account"}}, "__second_invalid__")
		dest := filepath.Join(root, "generated")
		if err := os.Mkdir(dest, 0700); err != nil {
			t.Fatal(err)
		}
		existing := filepath.Join(dest, "Account.d.ts")
		if err := os.WriteFile(existing, []byte("original"), 0600); err != nil {
			t.Fatal(err)
		}
		out, errs, status := runCLI(t, root, binary, "__second_invalid__", args...)
		if out != "" || errs != "sf-typings: invalid describe for Contact\n" || status != 1 {
			t.Fatalf("stdout=%q stderr=%q exit=%d", out, errs, status)
		}
		b, _ := os.ReadFile(existing)
		if string(b) != "original" {
			t.Fatalf("existing=%q", b)
		}
		if _, err := os.Stat(filepath.Join(dest, "Contact.d.ts")); !os.IsNotExist(err) {
			t.Fatalf("unexpected Contact output: %v", err)
		}
	})
	t.Run("invalid describe does not overwrite", func(t *testing.T) {
		root, binary, args := fixture(t, config, `{"status":0,"result":{"name":"Account","fields":[{"name":"Name","type":"string"}]}}`)
		dest := filepath.Join(root, "generated")
		if err := os.Mkdir(dest, 0700); err != nil {
			t.Fatal(err)
		}
		existing := filepath.Join(dest, "Account.d.ts")
		if err := os.WriteFile(existing, []byte("original"), 0600); err != nil {
			t.Fatal(err)
		}
		out, errs, status := runCLI(t, root, binary, `{"status":0,"result":{"name":"Account","fields":[{"name":"Name","type":"string"}]}}`, args...)
		if out != "" || errs != "sf-typings: invalid describe for Account\n" || status != 1 {
			t.Fatalf("stdout=%q stderr=%q exit=%d", out, errs, status)
		}
		b, _ := os.ReadFile(existing)
		if string(b) != "original" {
			t.Fatalf("existing=%q", b)
		}
	})
}

